CREATE TABLE data_quality_result_log
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    result_event_id    VARCHAR(255)                            NOT NULL,
    raw_event_id       VARCHAR(255)                            NOT NULL,
    provider           VARCHAR(255)                            NOT NULL,
    endpoint_key       VARCHAR(255)                            NOT NULL,
    api_id             VARCHAR(255)                            NOT NULL,
    canonical_hash     VARCHAR(255)                            NOT NULL,
    raw_json_object_key VARCHAR(1024)                          NOT NULL,
    scanner_version    VARCHAR(255)                            NOT NULL,
    checked_at         TIMESTAMP WITH TIME ZONE                NOT NULL,
    issue_count        INTEGER                                 NOT NULL,
    result_json        TEXT                                    NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_data_quality_result_log PRIMARY KEY (id),
    CONSTRAINT uk_data_quality_result_log_result_event_id UNIQUE (result_event_id)
);

CREATE INDEX idx_data_quality_result_log_provider_endpoint_api
    ON data_quality_result_log (provider, endpoint_key, api_id);

CREATE INDEX idx_data_quality_result_log_checked_at
    ON data_quality_result_log (checked_at);

CREATE INDEX idx_data_quality_result_log_issue_count
    ON data_quality_result_log (issue_count);

CREATE INDEX idx_data_quality_result_log_raw_event_id
    ON data_quality_result_log (raw_event_id);

CREATE INDEX idx_data_quality_result_log_canonical_hash
    ON data_quality_result_log (canonical_hash);

